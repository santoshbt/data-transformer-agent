from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
	messages: Annotated[list, add] = Field(..., description="A list of messages exchanged between the user and the agent.")
	user_question: str = Field(..., description="The original question asked by the user.")
	curated_ques: str = Field(..., description="curated user question")
	prompt_query_context: str = Field(..., description="A detailed prompt with SQL DB context and user question to be sent to the LLM for generating SQL query.")
	is_safe: Literal["Yes", "No"] = Field(..., description="Indicates whether the generated SQL query is safe to execute or not.")
	
	generated_sql_query: str = Field(..., description="The SQL query generated by the LLM based on the prompt and context provided.")
	comments:  str = Field(..., description="Comments regarding the safety of the generated SQL query")
	sql_query_execution_result: str = Field(..., description="The result of executing the generated SQL query against the database.")
	final_answer: str = Field(..., description="The final answer generated by the LLM based on the SQL query execution result and user question.")

class JudgeSchema(BaseModel):
	answer: Literal["Yes", "No"] = Field(..., description="Indicates whether the final answer provided by the agent is correct or not.")
	comments: str = Field(..., description="Any additional comments or feedback regarding the final answer provided by the agent.")


class ETLAgentSchema(BaseModel):
	messages: Annotated[list, add] = Field(..., description="List of messages to be processed by the ETL agent")


class RouterSchema(BaseModel):
    answer: Literal["sql","etl"] = Field(..., description="Indicates whether the user's question is related to SQL or ETL operations")
    comments: str = Field(..., description="Additional comments or feedback regarding the classification of the user's question")

class DataAgentSchema(BaseModel):
    messages : Annotated[list,add] = Field(..., description="List of messages to be processed by the Data agent")
    route_response: str = Field(default="", description="The response from the router indicating whether to route to SQL or ETL operations")